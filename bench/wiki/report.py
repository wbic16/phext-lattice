#!/usr/bin/env python3
"""Render wikibench JSON results as Markdown tables.  usage: report.py <work_dir> <scale>..."""
import json, os, sys


def load(work, s, name):
    p = os.path.join(work, f"s{s}", name)
    return json.load(open(p)) if os.path.exists(p) else {}


def lat(v, key="p50_us"):
    if not v:
        return "—"
    x = v[key]
    return f"{x / 1000:.1f} ms" if x >= 1000 else f"{x:.1f} µs"


def mb(b):
    return f"{b / 1e6:.2f} MB"


def table(head, rows):
    out = ["| " + " | ".join(head) + " |", "|" + "---|" * len(head)]
    out += ["| " + " | ".join(str(c) for c in r) + " |" for r in rows]
    return "\n".join(out) + "\n"


def main(work, *scales):
    print("# wikibench results\n")
    print("Generated by `bench/wiki/run_all.sh`. Corpus: `wikipedia_en_climate_change_mini_2024-06.zim` "
          "(Kiwix, openzim/zim-testing-suite), lead-section text. Scale N replicates the corpus N× with "
          "suffixed titles. Latencies are p50 (p99) per operation; ZIM numbers come from python-libzim "
          "(C++), everything else from Rust — see the Python calibration row.\n")
    for s in scales:
        r, z, st = load(work, s, "rust_results.json"), load(work, s, "zim_results.json"), load(work, s, "storage.json")
        if not r:
            continue
        print(f"## Scale {s}: {r['articles']:,} articles, {r['edges']:,} links, {mb(r['payload_bytes'])} payload\n")
        print("### Storage\n")
        rows = []
        for k, v in st.get("stores", {}).items():
            rows.append([k, mb(v["apparent_bytes"]), mb(v["allocated_bytes"]), f"{v['overhead_vs_payload']:.2f}×",
                         f"{v['inodes']:,}", mb(v["zstd19_bytes"]) if "zstd19_bytes" in v else "native"])
        print(table(["store", "apparent", "on disk", "disk / payload", "inodes", "zstd-19"], rows))
        if "phext_breakdown" in st:
            b = st["phext_breakdown"]
            print(f"phext: {b['delimiter_bytes']:,} delimiter bytes, {b['non_payload_bytes']:,} bytes of titles + link coordinates + aliases.\n")

        o = r["open"]
        print(f"### Open → first article (cold cache: {r.get('cold_cache')})\n")
        rows = [["files", f"{o['files']['open_first_ms']} ms", "—"],
                ["sqlite", f"{o['sqlite']['open_first_ms']} ms", f"{o['sqlite']['rss_kb'] / 1024:.1f} MB"],
                ["zim (py)", f"{z.get('open_first_ms', '—')} ms", "—"],
                ["phext: libphext read + fetch", f"{o['phext_libphext_fetch']['open_first_ms']} ms", f"{o['phext_libphext_fetch']['rss_kb'] / 1024:.1f} MB"],
                ["phext: libphext explode", f"{o['phext_libphext_explode']['open_first_ms']} ms (+read)", f"{o['phext_libphext_explode']['rss_kb'] / 1024:.1f} MB"],
                ["phext-lattice mmap + index + names", f"{o['phext_lattice']['open_first_ms']} ms (index {o['phext_lattice']['index_build_ms']}, names {o['phext_lattice']['name_map_ms']})", f"{o['phext_lattice']['rss_kb'] / 1024:.1f} MB"],
                ["SQ host (spawn + explode)", f"{o.get('sq_http', {}).get('open_first_ms', '—')} ms", "—"]]
        print(table(["store / access path", "time", "RSS added"], rows))

        lw = r["lookup_warm"]; zl = z.get("lookup_warm", {})
        print("### Warm lookup (title → article text)\n")
        rows = [["files (dirent)", lat(lw["files"]), lat(lw["files"], "p99_us")],
                ["sqlite (title index)", lat(lw["sqlite"]), lat(lw["sqlite"], "p99_us")],
                ["sqlite (rowid)", lat(lw["sqlite_by_id"]), lat(lw["sqlite_by_id"], "p99_us")],
                ["zim (title index, py)", lat(zl.get("zim_by_title")), lat(zl.get("zim_by_title"), "p99_us")],
                ["phext libphext::fetch (linear scan)", lat(lw["phext_libphext_fetch"]), lat(lw["phext_libphext_fetch"], "p99_us")],
                ["phext libphext::explode map", lat(lw["phext_libphext_explode"]), lat(lw["phext_libphext_explode"], "p99_us")],
                ["phext-lattice (name map + mmap)", lat(lw["phext_lattice"]), lat(lw["phext_lattice"], "p99_us")],
                ["phext-lattice (by coordinate)", lat(lw["phext_lattice_by_coord"]), lat(lw["phext_lattice_by_coord"], "p99_us")],
                ["SQ HTTP select (by coordinate)", lat(lw.get("sq_http_by_coord")), lat(lw.get("sq_http_by_coord"), "p99_us")],
                ["calibration: python sqlite3", lat(zl.get("py_sqlite_by_title")), lat(zl.get("py_sqlite_by_title"), "p99_us")],
                ["calibration: python file read", lat(zl.get("py_file_read")), lat(zl.get("py_file_read"), "p99_us")]]
        print(table(["access path", "p50", "p99"], rows))

        t = r["traversal_2hop"]; b = r["backlinks"]
        print(f"### Link traversal (2-hop BFS reading every node, mean {t['mean_nodes']:.0f} nodes) and backlinks\n")
        rows = [["files", lat(t["files"]), lat(t["files"], "p99_us"), lat(b["files_scan"]) + " (scan)"],
                ["sqlite", lat(t["sqlite"]), lat(t["sqlite"], "p99_us"), lat(b["sqlite"]) + " (index)"],
                ["zim (py)", lat(z.get("traversal_2hop")), lat(z.get("traversal_2hop"), "p99_us"), lat(z.get("backlinks_scan")) + " (scan)"],
                ["phext libphext explode map", lat(t["phext_libphext_explode"]), lat(t["phext_libphext_explode"], "p99_us"), "—"],
                ["phext-lattice", lat(t["phext_lattice"]), lat(t["phext_lattice"], "p99_us"), lat(b["phext_lattice_scan"]) + " (scan)"],
                ["SQ HTTP (select + query set)", lat(t.get("sq_http_query_api")), lat(t.get("sq_http_query_api"), "p99_us"), "—"]]
        print(table(["store", "BFS p50", "BFS p99", "backlinks p50"], rows))

        u = r["updates"]; a = u["append_new_article"]
        print("### Incremental updates (durable unless noted)\n")
        rows = [["files (rewrite + fsync)", lat(u["files"]), lat(a["files"])],
                ["sqlite WAL, synchronous=FULL, FTS triggers", lat(u["sqlite_with_fts"]), lat(a["sqlite_with_fts"])],
                ["zim", f"full rebuild {z.get('build_ms', 0) / 1000:.2f} s", "full rebuild"],
                ["phext libphext::replace + rewrite file", lat(u["phext_libphext_replace_rewrite"]), "—"],
                ["phext-lattice write_scroll + save()", lat(u["phext_lattice_save_each"]), "—"],
                ["phext-lattice 100 edits, one save()", f"{u['phext_lattice_batch_100_ms']} ms total", "—"],
                ["phext raw append at EOF + fsync", "—", lat(a["phext_raw_append"]) + f" (+{a['phext_lattice_reopen_after_append_ms']} ms re-index)"],
                ["SQ HTTP update (no fsync)", lat(u.get("sq_http_update")), "—"]]
        print(table(["path", "edit one article", "add one article"], rows))

        if "retrieval" in r:
            print("### Agent retrieval\n")
            rr, zr = r["retrieval"], z.get("retrieval", {})
            for kind in ("alias", "alias_lower"):
                rows = [[k, f"{v['hit_rate']:.3f}", lat(v["latency"])] for src in (rr.get(kind, {}), zr.get(kind, {})) for k, v in src.items()]
                print(f"**{kind}** ({'exact redirect title' if kind == 'alias' else 'lower-cased redirect title'})\n")
                print(table(["method", "hit rate", "p50"], rows))
            for kind in ("keywords", "keywords_hard"):
                rows = []
                for src in (rr.get(kind, {}), zr.get(kind, {})):
                    for k, v in src.items():
                        rows.append([k, v["queries"], f"{v['recall@1']:.3f}", f"{v['recall@10']:.3f}", f"{v['mrr@10']:.3f}",
                                     f"{v['context_bytes_p50']:,}", lat(v["latency"])])
                print(f"**{kind}**\n")
                print(table(["method", "n", "R@1", "R@10", "MRR@10", "agent bytes read (p50)", "p50"], rows))
            ti = rr["keywords"]["phext_lattice_term_index"]
            ni = rr.get("name_index", {})
            print(f"`NameIndex`: {ni.get('names', 0):,} names, {ni.get('ambiguous_folded', 0)} folded collisions, built as part of "
                  f"phext-lattice open (`names` above). `TermIndex` build: {ti['build_ms']} ms, ~{mb(ti['approx_heap_bytes'])} heap.\n")


if __name__ == "__main__":
    main(sys.argv[1], *sys.argv[2:])
